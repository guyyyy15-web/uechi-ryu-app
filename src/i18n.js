function getLang(){
  try{
    return localStorage.getItem('lang') === 'en' ? 'en' : 'he';
  }catch(e){
    return 'he';
  }
}

function setLang(lang){
  try{ localStorage.setItem('lang', lang); }catch(e){}
  applyI18n(lang);
}

function applyI18n(lang){
  const dict = I18N[lang] || I18N.he;
  document.documentElement.lang = lang;
  document.documentElement.dir = lang === 'en' ? 'ltr' : 'rtl';

  document.querySelectorAll('[data-i18n]').forEach(function(el){
    const key = el.getAttribute('data-i18n');
    if(dict[key] !== undefined) el.textContent = dict[key];
  });
  document.querySelectorAll('[data-i18n-html]').forEach(function(el){
    const key = el.getAttribute('data-i18n-html');
    if(dict[key] !== undefined) el.innerHTML = dict[key];
  });
  document.querySelectorAll('[data-i18n-attr]').forEach(function(el){
    el.getAttribute('data-i18n-attr').split(';').forEach(function(pair){
      const parts = pair.split(':');
      const attr = parts[0] && parts[0].trim();
      const key = parts[1] && parts[1].trim();
      if(attr && key && dict[key] !== undefined) el.setAttribute(attr, dict[key]);
    });
  });

  const langToggle = document.getElementById('langToggle');
  if(langToggle) langToggle.textContent = lang === 'he' ? 'EN' : 'עב';

  I18N_RERENDER.forEach(function(fn){
    try{ fn(lang); }catch(e){}
  });
}

const I18N_RERENDER = [];
function registerI18nRerender(fn){
  I18N_RERENDER.push(fn);
}
